"""Pinned independent oracle for dense embedding lookup and its linear Jacobian."""
from decimal import Decimal, localcontext
from pathlib import Path
import argparse, json
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
weights = list(map(Decimal, ['.25','-.5','1.5','2','-.75','.125','3','-2']))
indices = [2,0,2,1]
seed = list(map(Decimal, ['.2','-.3','.4','.5','-.6','.7','.8','-.9']))
cases = []
with localcontext() as context:
    context.prec = 50
    for padding in [None, 2]:
        output = [weights[row*2+c] for row in indices for c in range(2)]
        gradient = [Decimal(0)] * len(weights)
        for i,row in enumerate(indices):
            if row == padding: continue
            for c in range(2): gradient[row*2+c] += seed[i*2+c]
        cases.append(dict(padding_index=padding, output=list(map(str,output)), gradient=list(map(str,gradient))))
report = dict(oracle='Decimal 50 digits; direct row lookup and transpose of a fixed linear selection matrix',
              weights=list(map(str,weights)), indices=indices, seed=list(map(str,seed)), cases=cases,
              padding_contract='The padding row is read normally; its declared first-order derivative is stopped.')
def literals(values):
    return '[' + ','.join(str(v) if '.' in str(v) else str(v)+'.0' for v in values) + ']'
source = '''// Generated by Tools/Oracle/embedding_decimal.py; independent Decimal linear oracle.
use Tensor
use Tensor.Neural
use Tensor.Autograd
use GFX.GPU
use STD.Math
func oracle_embedding(device:GPU.Device?) {
'''
for case in cases:
    source += '    {\n'
    padding = '' if case['padding_index'] is None else ',padding_index:2'
    source += f'        var layer=Neural.Embedding("tokens",4,2,seed:7{padding})\n'
    source += f'        var weights:float[]={literals(weights)};var parameters=layer.parameters()\n'
    source += '        parameters[0].replace(Tensor(weights,[4,2]))\n'
    source += '        var ids:int32[]=[2,0,2,1];var input=Tensor(ids,[2,2])\n'
    source += f'        var seed_values:float[]={literals(seed)};var upstream=Tensor(seed_values,[2,2,2])\n'
    source += '        if let gpu=device {layer.to(gpu);input=input.to(gpu);upstream=upstream.to(gpu)}\n'
    source += '        let output=layer.forward(input);var gradients=Autograd.grad(output,[parameters[0].value()],seed:upstream)\n'
    source += f'        var expected_output:float[]={literals(case["output"])}\n'
    source += f'        var expected_gradient:float[]={literals(case["gradient"])}\n'
    source += '        let actual_output=output.detach().cpu().values();let actual_gradient=gradients[0].cpu().values()\n'
    source += '        var i=0;while i<8 {assert(Math.abs(actual_output[i]-expected_output[i])<0.000001);assert(Math.abs(actual_gradient[i]-expected_gradient[i])<0.000001);i++}\n'
    source += '    }\n'
source += '''}
test "Embedding CPU values and stopped padding derivatives match the independent Decimal fixture" {oracle_embedding(null)}
test "Embedding Metal values and stopped padding derivatives match the independent Decimal fixture" {
    if !GPU.Device.is_supported() {return}
    var device=GPU.Device(GPU.DeviceSettings(debug:true));oracle_embedding(device)
}
'''
files = {root/'Tools/Oracle/EMBEDDING_REPORT.json': json.dumps(report,indent=2)+'\n',
         root/'Tests/Consumer/Tests/EmbeddingOracle.sx': source}
for path,content in files.items():
    if args.check:
        if path.read_text() != content: raise SystemExit(f'Independent embedding oracle differs: {path}')
    else: path.write_text(content)
