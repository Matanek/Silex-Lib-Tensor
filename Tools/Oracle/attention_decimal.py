"""Independent Decimal scaled dot product attention and input VJP oracle."""
from decimal import Decimal, localcontext
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[2]


def generate():
    with localcontext() as context:
        context.prec = 60
        q = [[Decimal('0.125'), Decimal('-0.5')], [Decimal('0.75'), Decimal('0.25')]]
        k = [[Decimal('0.5'), Decimal('1.25')], [Decimal('-0.75'), Decimal('0.125')], [Decimal('0.25'), Decimal('-0.5')]]
        v = [[Decimal('1.5'), Decimal('-0.25')], [Decimal('0.5'), Decimal('0.75')], [Decimal('-1.25'), Decimal('2.0')]]
        seed = [[Decimal('0.2'), Decimal('-0.3')], [Decimal('0.7'), Decimal('-1.1')]]
        visible = [[False, False, False], [True, False, True]]
        cases = []
        for factor in [Decimal('0.5'), Decimal(1) / Decimal(2).sqrt()]:
            dq = [[Decimal(0)] * 2 for _ in q]
            dk = [[Decimal(0)] * 2 for _ in k]
            dv = [[Decimal(0)] * 2 for _ in v]
            weights, outputs = [], []
            for row, upstream, mask, q_gradient in zip(q, seed, visible, dq):
                scores = [sum(x * y for x, y in zip(row, key)) * factor for key in k]
                exps = [s.exp() if allow else Decimal(0) for s, allow in zip(scores, mask)]
                total = sum(exps)
                probabilities = [e / total if total else Decimal(0) for e in exps]
                weights.append(probabilities)
                outputs.append([sum(p * value[c] for p, value in zip(probabilities, v)) for c in range(2)])
                d_probability = [sum(g * x for g, x in zip(upstream, value)) for value in v]
                projection = sum(p * g for p, g in zip(probabilities, d_probability))
                d_score = [p * (g - projection) for p, g in zip(probabilities, d_probability)]
                for j, (probability, score_gradient) in enumerate(zip(probabilities, d_score)):
                    for c in range(2):
                        dv[j][c] += probability * upstream[c]
                        dk[j][c] += score_gradient * factor * row[c]
                        q_gradient[c] += score_gradient * factor * k[j][c]
            cases.append(dict(scale=str(factor), output=outputs, weights=weights, query_gradient=dq, key_gradient=dk, value_gradient=dv))
        def numbers(matrix):
            return '[' + ','.join(str(float(x)) for row in matrix for x in row) + ']'
        code = '''// Generated by Tools/Oracle/attention_decimal.py; independent Decimal attention and VJP.
use Tensor
use Tensor.Neural
use Tensor.Autograd
use GFX.GPU
use STD.Math

func attention_oracle_near(actual:Tensor, expected:float[]) {
    let values=actual.detach().cpu().values()
    assert(values.count()==expected.count())
    var i=0
    while i<values.count() {assert(Math.is_finite(values[i]) && Math.abs(values[i]-expected[i])<0.000002);i++}
}
func decimal_attention(device:GPU.Device?, default_scale:bool) {
'''
        code += '    var qs:float[]=' + numbers(q) + '\n'
        code += '    var ks:float[]=' + numbers(k) + '\n'
        code += '    var vs:float[]=' + numbers(v) + '\n'
        code += '    var seeds:float[]=' + numbers(seed) + '\n'
        code += '''    var flags:bool[]=[false,false,false,true,false,true]
    var q=Tensor(qs,[1,2,2]);var k=Tensor(ks,[1,3,2]);var v=Tensor(vs,[1,3,2]);var mask=Tensor(flags,[1,2,3]);var seed=Tensor(seeds,[1,2,2])
    if let gpu=device {q=q.to(gpu);k=k.to(gpu);v=v.to(gpu);mask=mask.to(gpu);seed=seed.to(gpu)}
    var query=Autograd.Variable(q);var key=Autograd.Variable(k);var value=Autograd.Variable(v)
    var scale:float?=0.5
    if default_scale {scale=null}
    let result=Neural.attention(query.value(),key.value(),value.value(),mask:mask,scale:scale,return_weights:true)
    var gradients=Autograd.grad(result.output,[query.value(),key.value(),value.value()],seed:seed)
'''
        for i, case in enumerate(cases):
            code += '    ' + ('if !default_scale {' if i == 0 else 'else {') + '\n'
            code += '        attention_oracle_near(result.output,' + numbers(case['output']) + ')\n'
            code += '        if let weights=result.weights {attention_oracle_near(weights,' + numbers(case['weights']) + ')}\n'
            code += '        else {panic("expected oracle attention weights")}\n'
            for j, field in enumerate(['query_gradient', 'key_gradient', 'value_gradient']):
                code += '        attention_oracle_near(gradients[' + str(j) + '],' + numbers(case[field]) + ')\n'
            code += '    }\n'
        code += '''}
test "attention explicit and default scale outputs and QKV gradients match Decimal on CPU" {decimal_attention(null,false);decimal_attention(null,true)}
test "attention explicit and default scale outputs and QKV gradients match Decimal on Metal" {
    if !GPU.Device.is_supported() {return}
    var device=GPU.Device(GPU.DeviceSettings(debug:true));decimal_attention(device,false);decimal_attention(device,true)
}
'''
        report = dict(precision=60, source='Direct Decimal exp-normalized dot products and analytic QKV VJP', query=q, key=k, value=v, seed=seed, visibility=visible, cases=cases, input_conversion='Raw row-major [batch,sequence,features], no parameters, transposition or gate conversion', absolute_tolerance=0.000002)
        return {ROOT / 'Tests/Consumer/Tests/AttentionOracle.sx': code, ROOT / 'Tools/Oracle/ATTENTION_REPORT.json': json.dumps(report, default=str, indent=2) + '\n'}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Fixture mismatch: ' + str(path))
        else:
            path.write_text(content)
    print('Attention Decimal fixtures verified' if args.check else 'Attention Decimal fixtures generated')


if __name__ == '__main__':
    main()
