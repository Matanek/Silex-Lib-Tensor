"""Independent Decimal projected two-head attention and analytic input/parameter VJP."""
from decimal import Decimal, localcontext
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[2]


def matrix(rows):
    return [[Decimal(str(x)) for x in row] for row in rows]


def zeros(rows, columns):
    return [[Decimal(0)] * columns for _ in range(rows)]


def linear(inputs, weight, bias):
    return [[sum(x * weight[i][j] for i, x in enumerate(row)) + bias[j]
             for j in range(2)] for row in inputs]


def linear_vjp(inputs, weight, upstream):
    dx = [[sum(g * weight[i][j] for j, g in enumerate(row)) for i in range(2)]
          for row in upstream]
    dw = [[sum(row[i] * grad[j] for row, grad in zip(inputs, upstream))
           for j in range(2)] for i in range(2)]
    db = [sum(row[j] for row in upstream) for j in range(2)]
    return dx, dw, db


def flat(value):
    return [x for row in value for x in row] if value and isinstance(value[0], list) else value


def literal(value):
    return '[' + ','.join(str(float(x)) for x in flat(value)) + ']'


def generate():
    with localcontext() as context:
        context.prec = 60
        q = matrix([[0.125, -0.5], [0.75, 0.25], [-0.25, 0.5]])
        k = matrix([[0.5, 1.25], [-0.75, 0.125], [0.25, -0.5]])
        v = matrix([[1.5, -0.25], [0.5, 0.75], [-1.25, 2]])
        seed = matrix([[0.2, -0.3], [0.7, -1.1], [-0.4, 0.8]])
        weights = [matrix([[0.5, -0.25], [0.75, 0.125]]),
                   matrix([[0.25, 0.75], [-0.5, 0.5]]),
                   matrix([[1, -0.25], [0.5, 0.75]]),
                   matrix([[0.75, 0.25], [-0.5, 1.25]])]
        biases = [[Decimal(x) for x in row] for row in
                  [['0.1', '-0.2'], ['-0.05', '0.15'], ['0.2', '-0.1'], ['0.3', '-0.2']]]
        visibility = [[[False, False, False], [True, False, True], [False, False, False]],
                      [[False, False, False], [False, True, True], [True, False, True]]]
        qp, kp, vp = [linear(x, w, b) for x, w, b in zip([q, k, v], weights, biases)]
        probabilities = []
        mixed = zeros(3, 2)
        dq, dk, dv = zeros(3, 2), zeros(3, 2), zeros(3, 2)
        active = [any(any(head[i]) for head in visibility) for i in range(3)]
        upstream = [[x if active[i] else Decimal(0) for x in row] for i, row in enumerate(seed)]
        for head in range(2):
            head_probabilities = []
            for i in range(3):
                exps = [(qp[i][head] * kp[j][head]).exp() if visibility[head][i][j]
                        else Decimal(0) for j in range(3)]
                total = sum(exps)
                p = [x / total if total else Decimal(0) for x in exps]
                head_probabilities.append(p)
                mixed[i][head] = sum(p[j] * vp[j][head] for j in range(3))
            probabilities.append(head_probabilities)
        output = linear(mixed, weights[3], biases[3])
        output = [row if active[i] else [Decimal(0), Decimal(0)] for i, row in enumerate(output)]
        dmixed, dwo, dbo = linear_vjp(mixed, weights[3], upstream)
        for head in range(2):
            for i in range(3):
                p = probabilities[head][i]
                dp = [dmixed[i][head] * row[head] for row in vp]
                projection = sum(x * g for x, g in zip(p, dp))
                ds = [x * (g - projection) for x, g in zip(p, dp)]
                dq[i][head] = sum(ds[j] * kp[j][head] for j in range(3))
                for j in range(3):
                    dk[j][head] += ds[j] * qp[i][head]
                    dv[j][head] += p[j] * dmixed[i][head]
        gradients = [linear_vjp(x, w, d) for x, w, d in zip([q, k, v], weights, [dq, dk, dv])]
        parameter_values = [item for pair in zip(weights, biases) for item in pair]
        parameter_gradients = [item for dx, dw, db in gradients for item in [dw, db]] + [dwo, dbo]
        names = ['attention.' + part + '.' + slot for part in ['query', 'key', 'value', 'output']
                 for slot in ['weight', 'bias']]
        code = '''// Generated by Tools/Oracle/multihead_decimal.py; independent Decimal projections and VJP.
use Tensor
use Tensor.Neural
use Tensor.Autograd
use GFX.GPU
use STD.Math

func multihead_oracle_near(actual:Tensor, expected:float[]) {
    let data=actual.detach().cpu().values()
    assert(data.count()==expected.count())
    var i=0;while i<data.count() {assert(Math.is_finite(data[i]) && Math.abs(data[i]-expected[i])<0.000003);i++}
}
func decimal_multihead(device:GPU.Device?) {
    var model=Neural.MultiHeadAttention("attention",2,2,seed:19)
    var parameters=model.parameters()
'''
        for i, (name, data) in enumerate(zip(names, parameter_values)):
            code += '    assert(parameters[' + str(i) + '].name()=="' + name + '")\n'
            code += '    var p' + str(i) + '=parameters[' + str(i) + ']\n'
            code += '    var data' + str(i) + ':float[]=' + literal(data) + '\n'
            code += '    p' + str(i) + '.replace(Tensor(data' + str(i) + ',' + ('[2,2]' if i % 2 == 0 else '[2]') + '))\n'
        for name, data in [('qs', q), ('ks', k), ('vs', v), ('seeds', seed)]:
            code += '    var ' + name + ':float[]=' + literal(data) + '\n'
        flags = [flag for head in visibility for row in head for flag in row]
        code += '    var flags:bool[]=[' + ','.join(str(x).lower() for x in flags) + ']\n'
        code += '''    var q=Tensor(qs,[1,3,2]);var k=Tensor(ks,[1,3,2]);var v=Tensor(vs,[1,3,2]);var seed=Tensor(seeds,[1,3,2]);var mask=Tensor(flags,[1,2,3,3])
    if let gpu=device {model.to(gpu);q=q.to(gpu);k=k.to(gpu);v=v.to(gpu);seed=seed.to(gpu);mask=mask.to(gpu)}
    var query=Autograd.Variable(q);var key=Autograd.Variable(k);var value=Autograd.Variable(v)
    var inputs:Tensor[]=[query.value(),key.value(),value.value()]
    for parameter in parameters {inputs.append(parameter.value())}
    let result=model.attend(query.value(),key.value(),value.value(),mask:mask,return_weights:true)
    var gradients=Autograd.grad(result.output,inputs,seed:seed)
'''
        code += '    multihead_oracle_near(result.output,' + literal(output) + ')\n'
        all_probabilities = [row for head in probabilities for row in head]
        code += '    if let weights=result.weights {multihead_oracle_near(weights,' + literal(all_probabilities) + ')} else {panic("expected attention weights")}\n'
        for i, data in enumerate([x[0] for x in gradients] + parameter_gradients):
            code += '    multihead_oracle_near(gradients[' + str(i) + '],' + literal(data) + ')\n'
        code += '''}
test "projected two-head attention matches Decimal input and all parameter gradients on CPU" {decimal_multihead(null)}
test "projected two-head attention matches Decimal input and all parameter gradients on Metal" {
    if !GPU.Device.is_supported() {return}
    var device=GPU.Device(GPU.DeviceSettings(debug:true));decimal_multihead(device)
}
'''
        report = dict(precision=60, query=q, key=k, value=v, seed=seed, heads=2, head_features=1,
                      parameter_names=names, parameter_values=parameter_values, parameter_gradients=parameter_gradients,
                      visibility=visibility, output=output, weights=probabilities, input_gradients=[x[0] for x in gradients],
                      conversion='Four separate row-major [input,output] weights; biases in output order; heads select contiguous projected feature groups; no framework packing',
                      absolute_tolerance=0.000003)
        return {ROOT / 'Tests/Consumer/Tests/MultiHeadAttentionOracle.sx': code,
                ROOT / 'Tools/Oracle/MULTIHEAD_REPORT.json': json.dumps(report, default=str, indent=2) + '\n'}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Fixture mismatch: ' + str(path))
        else:
            path.write_text(content)
    print('Multi-head Decimal fixtures verified' if args.check else 'Multi-head Decimal fixtures generated')


if __name__ == '__main__':
    main()
